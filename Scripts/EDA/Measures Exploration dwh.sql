--4-Measure Exploration
---------------------------------------------------
--Find the total Sales:
select sum(sale_amount) AS Total_Sales from gold.fact_sales;

-- Find how many items are sold:
select sum(quantity) AS Total_Quantity from gold.fact_sales;

-- Find the average selling price
select avg(price) AS Average_price from gold.fact_sales;

-- Find the Total number of Orders
select count(distinct order_number) AS total_orders from gold.fact_sales;
select count(order_number) AS total_orders from gold.fact_sales;

-- Find the total number of products
select count( product_name)  AS total_products from gold.dim_products

-- Find the total number of customers
select count(customer_key) as total_customers from gold.dim_customers

-- Find the total number of customers that has placed an order
select count(distinct customer_key) AS tto from gold.fact_sales

-- Generate a Report that shows all key metrics of the business
select 'total_sales' as measure_name,sum(sale_amount) as measure_value from gold.fact_sales
union all
select 'total_quantity',sum(quantity) from gold.fact_sales
union all
select 'average_price',avg(price) from gold.fact_sales
union all
select 'total_orders', count(distinct order_number) from gold.fact_sales
union all
select 'total_products',count(product_name) from gold.dim_products
union all 
select 'total_customers', count(customer_key) from gold.dim_customers
union all 
select 'total_customers_place_orders',count(distinct customer_key) from gold.fact_sales;

---------------------------------------------------
--5-Magnitude Analysis
---------------------------------------------------
-- Find total customers by countries
select country,
	count(customer_key) as total_customer_by_country 
from gold.dim_customers
group by country
order by total_customer_by_country desc

-- Find total customers by gender
select gender,
	count(customer_key) as total_customer_by_gender
from gold.dim_customers
group by gender
order by total_customer_by_gender

-- Find total products by category
select category,
	count(product_name) As total_products_by_category
from gold.dim_products
group by category
order by total_products_by_category desc

-- What is the average cost in each category?
select category,
	avg(product_cost) as total_cost_by_category
from gold.dim_products
group by category
order by total_cost_by_category desc

-- What is the total revenue generated for each category?
SELECT
    p.category,
    SUM(s.sale_amount) AS total_revenue
FROM gold.fact_sales s
LEFT JOIN gold.dim_products p
    ON p.product_key = s.product_key
GROUP BY p.category
ORDER BY total_revenue DESC;

-- What is the total revenue generated by each customer?

select c.customer_key,
	   c.first_name,
	   c.last_name,
	sum(s.sale_amount) as total_revenue_by_customer
from gold.fact_sales s
left join gold.dim_customers c
on c.customer_key = s.customer_key
group by c.customer_key,
	     c.first_name,
		 c.last_name
order by total_revenue_by_customer desc

-- What is the distribution of sold items across countries?
select c.country,
      sum(s.quantity) as sold_items_across_countries
from gold.fact_sales s
left join gold.dim_customers c
on c.customer_key =s.customer_key
group by c.country
order by sold_items_across_countries desc

---------------------------------------------------
--5-Ranking Analysis
---------------------------------------------------	
select* from gold.dim_customers;
select* from gold.dim_products;
select* from gold.fact_sales;

-- Which 5 products generate the Highest Revenue?
select*
from(
	select p.product_name,
		sum(s.sale_amount) as total_Revenue,
		rank() over( order by sum(s.sale_amount) desc) as ranked
	from gold.fact_sales s
	left join gold.dim_products p
	on p.product_key=s.product_key
	group by p.product_name
	) as ranked
where ranked <=5

-- What are the 5 worst-performing products in terms of sales?
select*
from(
	select p.product_name,
		sum(s.sale_amount) as total_Revenue,
		rank() over( order by sum(s.sale_amount) ) as ranked
	from gold.fact_sales s
	left join gold.dim_products p
	on p.product_key=s.product_key
	group by p.product_name
	) as ranked
where ranked <=5

-- Find the top 10 customers who have generated the highest revenue
select top 10
	c.customer_key,
	c.first_name,
	c.last_name,
	sum(s.sale_amount) as total_revenue
from gold.fact_sales s
left join gold.dim_customers c
on c.customer_key= s.customer_key
group by c.customer_key,c.first_name,c.last_name
order by total_revenue DESC


-- The 3 customers with the fewest orders placed
select* from gold.fact_sales
select top 3
	c.customer_key,
	c.first_name,
	c.last_name,
	count( distinct s.order_number) as total_order
from gold.fact_sales s
left join gold.dim_customers c
on c.customer_key= s.customer_key
group by c.customer_key,c.first_name,c.last_name
order by total_order

